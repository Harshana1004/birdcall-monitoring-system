@router.get(
    "/{recording_id}/detections",
    response_model=list[
        DetectionResponse
    ],
    responses={
        404: {
            "model": ErrorResponse,
            "description": (
                "Recording not found."
            ),
        },
    },
)
async def get_recording_detections(
    recording_id: uuid.UUID,
    session: DatabaseSession,
) -> list[
    DetectionResponse
]:
    """
    Return all BirdNET detections belonging to one recording.

    An empty list means that the recording exists but BirdNET
    produced no predictions above the configured confidence
    threshold.
    """

    recording = await session.get(
        Recording,
        recording_id,
    )

    if recording is None:
        raise RecordingNotFoundError(
            f"Recording '{recording_id}' was not found."
        )

    statement = (
        select(Detection)
        .where(
            Detection.recording_id
            == recording_id
        )
        .order_by(
            Detection.confidence.desc(),
            Detection.start_time_seconds.asc(),
        )
    )

    result = await session.execute(
        statement
    )

    detections = (
        result.scalars()
        .all()
    )

    return [
        DetectionResponse.model_validate(
            detection
        )
        for detection in detections
    ]


# ============================================================
# Get recording
# ============================================================


@router.get(
    "/{recording_id}",
    response_model=RecordingResponse,
    responses={
        404: {
            "model": ErrorResponse,
            "description": (
                "Recording not found."
            ),
        },
    },
)
async def get_recording(
    recording_id: uuid.UUID,
    session: DatabaseSession,
) -> RecordingResponse:
    """
    Return one recording by UUID.
    """

    service = RecordingService(
        session
    )

    recording = (
        await service.get_recording(
            recording_id
        )
    )

    return RecordingResponse.model_validate(
        recording
    )


