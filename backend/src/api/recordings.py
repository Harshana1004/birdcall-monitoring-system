@router.post(
    "",
    response_model=RecordingUploadResponse,
    status_code=status.HTTP_201_CREATED,
    responses={
        200: {
            "model": RecordingUploadResponse,
            "description": (
                "Idempotent retry. The existing recording "
                "is returned."
            ),
        },
        404: {
            "model": ErrorResponse,
            "description": (
                "Device not found."
            ),
        },
        409: {
            "model": ErrorResponse,
            "description": (
                "Inactive device, duplicate content or "
                "reused upload identifier."
            ),
        },
        413: {
            "model": ErrorResponse,
            "description": (
                "Uploaded file is too large."
            ),
        },
        422: {
            "model": ErrorResponse,
            "description": (
                "Invalid audio file or ROI metadata."
            ),
        },
    },
)
async def upload_recording(
    background_tasks: BackgroundTasks,
    response: Response,
    session: DatabaseSession,

    device_id: Annotated[
        uuid.UUID,
        Form(
            description=(
                "Database UUID of the device uploading "
                "the ROI snippet."
            ),
        ),
    ],

    client_upload_id: Annotated[
        uuid.UUID,
        Form(
            description=(
                "UUID generated by the ESP32 for "
                "retry-safe upload handling."
            ),
        ),
    ],

    capture_session_id: Annotated[
        uuid.UUID,
        Form(
            description=(
                "UUID shared by all snippets from one "
                "continuous capture session."
            ),
        ),
    ],

    snippet_sequence: Annotated[
        int,
        Form(
            ge=0,
            description=(
                "Zero-based ROI sequence number within "
                "the capture session."
            ),
        ),
    ],

    capture_started_at: Annotated[
        datetime,
        Form(
            description=(
                "Timezone-aware start timestamp of the "
                "continuous capture session."
            ),
        ),
    ],

    roi_start_seconds: Annotated[
        float,
        Form(
            ge=0,
            description=(
                "Start of this ROI relative to the "
                "continuous capture session."
            ),
        ),
    ],

    roi_end_seconds: Annotated[
        float,
        Form(
            gt=0,
            description=(
                "End of this ROI relative to the "
                "continuous capture session."
            ),
        ),
    ],

    edge_processing_version: Annotated[
        str,
        Form(
            min_length=1,
            max_length=100,
            description=(
                "Version of the ESP32 ROI-processing "
                "pipeline."
            ),
        ),
    ],

    edge_processing_metadata: Annotated[
        str,
        Form(
            description=(
                "JSON object describing normalization, "
                "energy detection, filtering and firmware "
                "parameters."
            ),
        ),
    ],

    audio_file: Annotated[
        UploadFile,
        File(
            description=(
                "Preprocessed mono PCM WAV ROI snippet."
            ),
        ),
    ],

    latitude: Annotated[
        Decimal | None,
        Form(
            ge=-90,
            le=90,
            description=(
                "Optional latitude captured by the device."
            ),
        ),
    ] = None,

    longitude: Annotated[
        Decimal | None,
        Form(
            ge=-180,
            le=180,
            description=(
                "Optional longitude captured by the device."
            ),
        ),
    ] = None,
) -> RecordingUploadResponse:
    """
    Upload one processed ROI snippet.

    Newly created recordings are scheduled for BirdNET
    classification.

    Idempotent retries return the existing recording without
    scheduling BirdNET again.
    """

    # --------------------------------------------------------
    # Parse multipart JSON metadata
    # --------------------------------------------------------

    parsed_edge_metadata = (
        parse_edge_processing_metadata(
            edge_processing_metadata
        )
    )

    # --------------------------------------------------------
    # Validate upload metadata
    # --------------------------------------------------------

    upload_metadata = (
        RecordingUploadMetadata(
            client_upload_id=(
                client_upload_id
            ),

            capture_session_id=(
                capture_session_id
            ),

            snippet_sequence=(
                snippet_sequence
            ),

            capture_started_at=(
                capture_started_at
            ),

            roi_start_seconds=(
                roi_start_seconds
            ),

            roi_end_seconds=(
                roi_end_seconds
            ),

            edge_processing_version=(
                edge_processing_version
            ),

            edge_processing_metadata=(
                parsed_edge_metadata
            ),

            latitude=latitude,
            longitude=longitude,
        )
    )

    # --------------------------------------------------------
    # Store recording
    # --------------------------------------------------------

    service = RecordingService(
        session
    )

    result = await service.upload_recording(
        device_id=device_id,
        upload=audio_file,
        metadata=upload_metadata,
    )

    # --------------------------------------------------------
    # New upload
    # --------------------------------------------------------

    if result.created:
        response.status_code = (
            status.HTTP_201_CREATED
        )

        message = (
            "ROI recording uploaded successfully."
        )

        background_tasks.add_task(
            process_recording_background,
            result.recording.id,
        )

    # --------------------------------------------------------
    # Idempotent retry
    # --------------------------------------------------------

    else:
        response.status_code = (
            status.HTTP_200_OK
        )

        message = (
            "The upload was already completed. "
            "The existing recording has been returned."
        )

    return RecordingUploadResponse(
        message=message,
        created=result.created,
        recording=(
            RecordingResponse.model_validate(
                result.recording
            )
        ),
    )


