@router.get(
    "",
    response_model=PaginatedResponse[
        RecordingSummaryResponse
    ],
)
async def list_recordings(
    session: DatabaseSession,

    page: Annotated[
        int,
        Query(
            ge=1,
            description="Page number.",
        ),
    ] = 1,

    page_size: Annotated[
        int,
        Query(
            ge=1,
            le=100,
            description=(
                "Number of recordings returned per page."
            ),
        ),
    ] = 20,

    device_id: Annotated[
        uuid.UUID | None,
        Query(
            description=(
                "Return recordings from a specific device."
            ),
        ),
    ] = None,

    capture_session_id: Annotated[
        uuid.UUID | None,
        Query(
            description=(
                "Return ROI snippets from one capture "
                "session."
            ),
        ),
    ] = None,

    processing_status: Annotated[
        ProcessingStatus | None,
        Query(
            description=(
                "Return recordings with a particular "
                "BirdNET processing status."
            ),
        ),
    ] = None,
) -> PaginatedResponse[
    RecordingSummaryResponse
]:
    """
    Return a paginated list of uploaded ROI recordings.
    """

    service = RecordingService(
        session
    )

    return await service.list_recordings(
        page=page,
        page_size=page_size,
        device_id=device_id,
        capture_session_id=(
            capture_session_id
        ),
        processing_status=(
            processing_status
        ),
    )


